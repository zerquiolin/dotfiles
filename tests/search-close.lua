local dir = vim.fn.tempname()
vim.fn.mkdir(dir, "p")
dir = vim.uv.fs_realpath(dir)
vim.fn.writefile({ "first" }, dir .. "/first.txt")
vim.fn.writefile({ "search match" }, dir .. "/match.txt")
vim.cmd.edit(dir .. "/first.txt")
local tabs = #vim.api.nvim_list_tabpages()
local actions = require("fzf-lua.actions")
actions.file_edit_or_qf({ dir .. "/match.txt:1:1:search match" }, {})
assert(vim.api.nvim_buf_get_name(0) == dir .. "/match.txt", "Search must open selected file")
assert(#vim.api.nvim_list_tabpages() == tabs, "Enter should not create a new tab")
local mapping = vim.fn.maparg(" q", "n", false, true)
assert(type(mapping.callback) == "function", "Close-view handler missing")
assert(vim.fn.maparg(" qq", "n") == "", "Longer mapping must not delay Space-q")
vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes("<Space>q", true, false, true), "xt", false)
assert(vim.api.nvim_buf_get_name(0) ~= dir .. "/match.txt", "Space-q should close the selected file")
assert(#vim.api.nvim_list_tabpages() == tabs, "Closing a buffer should keep the editor open")
print("PASS grep Enter opens in same tab; Space-q closes file with unsaved-change protection")
vim.cmd("qa!")
